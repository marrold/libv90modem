#!/usr/bin/env python3
"""Generate v90/v90_pcm_tab.c: the signed linear value of every octet of
both laws (v90_octet_linear, v90/v90_pcm.h), from V.90 Table 1's closed
form (v90/v90_pcm.c). With chord c = Ucode >> 4 and step s = Ucode & 15:
  mu-law  Ucode = 0x7F - (octet & 0x7F)
          linear = ((2s + 33) << (c + 2)) - 132
  A-law   Ucode = (octet ^ 0x55) & 0x7F
          linear = (2s + 1) << 3 for chord 0, (2s + 33) << (c + 2) above
negative when the octet's MSB is 0. test/test_small_exact.c checks the
table against the formula for all 512 entries.
Run: python3 tools/gen_pcm_lin.py > v90/v90_pcm_tab.c
"""

def ucode_linear(alaw, u):
    c, s = u >> 4, u & 15
    if alaw:
        return (2 * s + 1) << 3 if c == 0 else (2 * s + 33) << (c + 2)
    return ((2 * s + 33) << (c + 2)) - 132

def octet_linear(alaw, o):
    u = ((o ^ 0x55) & 0x7F) if alaw else 0x7F - (o & 0x7F)
    v = ucode_linear(alaw, u)
    return v if o & 0x80 else -v

print("/* GENERATED by tools/gen_pcm_lin.py - do not edit. */")
print("#include \"v90_pcm.h\"")
print("")
print("/* [0] mu-law, [1] A-law; indexed by the octet */")
print("const int16_t v90_octet_lin[2][256] = {")
for alaw in (0, 1):
    v = [octet_linear(alaw, o) for o in range(256)]
    assert all(-32768 <= x <= 32767 for x in v)
    print("  {")
    for r in range(0, 256, 16):
        print("    " + ",".join("%d" % x for x in v[r:r + 16]) + ",")
    print("  }," if alaw == 0 else "  }")
print("};")

#!/usr/bin/env python3
"""Receive band-passes for V.21, Kaiser-windowed sinc, linear phase. Pure python.
Default: the low channel (980 / 1180 Hz) of the answering modem, which keeps
the echo of our own high channel (1650 / 1850 Hz) and of ANSam (2100 Hz) out
of its carrier detector: writes modem/v21_bpf.h. --high: the high channel
(1650 / 1850 Hz) of the calling modem, keeping the echo of its own low channel
out: writes modem/v21h_bpf.h. bell103: the Bell 103 originate channel
(1070 / 1270 Hz) of the answering modem against our 2025 / 2225 Hz: writes
modem/bell103_bpf.h."""
import math, sys

FS = 8000.0
N = 81
HIGH = "--high" in sys.argv
BELLH = "bell103h" in sys.argv
BELL = "bell103" in sys.argv and not BELLH
V23H = "v23h" in sys.argv
V23 = "v23" in sys.argv and not V23H
if BELLH:
    LO, HI, CENTRE = 1805.0, 2445.0, 2125.0
    NAME, WHAT, SHOW = "bell103h_bpf", "Bell 103 answer-channel", (1070, 1270, 1650, 2025, 2100, 2225, 2250)
elif BELL:
    LO, HI, CENTRE = 850.0, 1490.0, 1170.0                 # -6 dB points
    NAME, WHAT, SHOW = "bell103_bpf", "Bell 103 originate-channel", (1070, 1270, 2025, 2100, 2225)
elif V23H:
    # calling modem's forward-channel receiver (1200 baud, 1300/2100 Hz): a
    # wide pass that keeps the whole 1200-baud signal yet rejects the echo of
    # our own 390/450 Hz backward channel.
    LO, HI, CENTRE = 800.0, 3400.0, 1700.0
    NAME, WHAT, SHOW = "v23h_bpf", "V.23 forward-channel", (300, 390, 450, 600, 880, 1300, 1700, 2100, 2700, 3000)
elif V23:
    # answering modem's backward-channel receiver (75 baud, 390/450 Hz): a
    # narrow low pass that rejects the echo of our own 1300/2100 Hz forward
    # channel.
    LO, HI, CENTRE = 300.0, 560.0, 420.0
    NAME, WHAT, SHOW = "v23_bpf", "V.23 backward-channel", (200, 300, 390, 450, 560, 1300, 2100)
elif HIGH:
    LO, HI, CENTRE = 1430.0, 2070.0, 1750.0
    NAME, WHAT, SHOW = "v21h_bpf", "V.21 high-channel", (980, 1180, 1650, 1850, 2100)
else:
    LO, HI, CENTRE = 760.0, 1400.0, 1080.0
    NAME, WHAT, SHOW = "v21_bpf", "V.21 low-channel", (980, 1180, 1650, 1850, 2100)
FILE = "modem/%s.h" % NAME
BETA = 4.5

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def taps():
    h = []
    m = (N - 1) / 2.0
    for n in range(N):
        t = n - m
        if t == 0:
            v = 2 * (HI - LO) / FS
        else:
            v = (math.sin(2 * math.pi * HI * t / FS) - math.sin(2 * math.pi * LO * t / FS)) / (math.pi * t)
        w = i0(BETA * math.sqrt(1 - (t / m) ** 2)) / i0(BETA)
        h.append(v * w)
    return h

def gain(h, f):
    re = sum(c * math.cos(2 * math.pi * f * n / FS) for n, c in enumerate(h))
    im = sum(c * math.sin(2 * math.pi * f * n / FS) for n, c in enumerate(h))
    return math.hypot(re, im)

h = taps()
g0 = gain(h, CENTRE)
q = [int(round(c / g0 * 32768)) for c in h]
hq = [c / 32768.0 for c in q]
def db(f): return 20 * math.log10(max(gain(hq, f), 1e-9))
report = {f: db(f) for f in (200, 300, 390, 450, 560, 600, 880, 980, 1070, 1080, 1180, 1270, 1280, 1300, 1500, 1650, 1700, 1850, 2025, 2100, 2225, 2250, 2550, 2700, 3000, 3400)}
if "--check" in sys.argv:
    for f, v in report.items(): print("%5d Hz %7.2f dB" % (f, v))
    sys.exit(0)
out = ["/* Generated by tools/gen_v21_bpf.py: do not edit.",
       " * %s receive band-pass, %d taps, Q15, linear phase." % (WHAT, N),
       " * Response: " + ", ".join("%d Hz %.1f dB" % (f, v) for f, v in report.items() if f in SHOW) + " */",
       "#ifndef V90D_MODEM_%s_H" % NAME.upper(), "#define V90D_MODEM_%s_H" % NAME.upper(), "#include <stdint.h>",
       "#define %s_N %d" % (NAME.upper(), N), "static const int16_t %s[%s_N] = {" % (NAME, NAME.upper())]
for i in range(0, N, 9):
    out.append("    " + ", ".join("%6d" % v for v in q[i:i + 9]) + ",")
out += ["};", "#endif", ""]
open(FILE, "w").write("\n".join(out))
